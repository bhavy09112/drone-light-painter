/**
 * Lua script exporter for ArduPilot light painting missions.
 * Generates experimental Copter GUIDED scripts; simulator validation is required.
 * 
 * The generated scripts use only standard ArduPilot Lua API functions
 * and avoid coroutines for compatibility.
 */

import { Shape, ExportConfig, PathSegment } from '@/shared/types';
import { analyzeSafety } from '../safety/safetyAnalyzer';
import { shapeToPathSegments, shapeStrokeLength } from '@/renderer/geometry/geometryEngine';

export interface ExportResult {
  script: string;
  stats: {
    pointCount: number;
    strokeCount: number;
    totalLength: number;
  };
}

/**
 * Export shapes to a complete ArduPilot Lua script.
 */
export function exportToLua(
  shapes: Shape[],
  config: ExportConfig
): ExportResult {
  const analysis = analyzeSafety(shapes, config);
  if (!analysis.canExport) throw new Error(analysis.issues.filter(i => i.severity === 'error').map(i => i.message).join('; '));
  const segments = shapes.flatMap(shape => shapeToPathSegments(shape));
  
  let pointCount = 0;
  let strokeCount = segments.length;
  let totalLength = 0;
  
  for (const shape of shapes) {
    totalLength += shapeStrokeLength(shape);
  }
  
  for (const segment of segments) {
    pointCount += segment.points.length;
  }
  
  const script = generateLuaScript(segments, config, {
    pointCount,
    strokeCount,
    totalLength,
  });
  
  return {
    script,
    stats: {
      pointCount,
      strokeCount,
      totalLength,
    },
  };
}

/**
 * Generate the complete Lua script.
 */
function generateLuaScript(
  segments: PathSegment[],
  config: ExportConfig,
  stats: { pointCount: number; strokeCount: number; totalLength: number }
): string {
  const lines: string[] = [];
  
  // Script header
  lines.push('-- ===============================================');
  lines.push('-- ArduPilot Light Painting Script');
  lines.push('-- Generated by Drone Light Painter');
  lines.push('-- ===============================================');
  lines.push('');
  lines.push('-- Configuration');
  lines.push(`local DRAW_SPEED = ${config.drawSpeed} -- m/s`);
  lines.push(`local MOVE_SPEED = ${config.moveSpeed} -- m/s`);
  lines.push(`local WAIT_TIME = ${config.waitTime} -- seconds`);
  lines.push(`local ALTITUDE = ${config.altitude} -- meters`);
  lines.push(`local RELAY_INDEX = ${config.relayIndex} -- relay pin index`);
  lines.push(`local DRY_RUN = ${config.dryRun ? 'true' : 'false'} -- set to true for testing without light`);
  lines.push('');
  lines.push('-- Mission Statistics');
  lines.push(`-- Total points: ${stats.pointCount}`);
  lines.push(`-- Total strokes: ${stats.strokeCount}`);
  lines.push(`-- Total path length: ${stats.totalLength.toFixed(2)} meters`);
  lines.push('');
  
  // Generate point data
  lines.push('-- ===============================================');
  lines.push('-- Point Data');
  lines.push('-- Format: {x, y, is_stroke}');
  lines.push('-- is_stroke: true for drawing, false for moving');
  lines.push('-- ===============================================');
  lines.push('');
  lines.push('local points = {');
  
  for (const segment of segments) {
    for (let i = 0; i < segment.points.length; i++) {
      const point = segment.points[i];
      const isStroke = i > 0 && segment.isStroke;
      lines.push(`  {${point.x.toFixed(2)}, ${point.y.toFixed(2)}, ${isStroke ? 'true' : 'false'}}, -- Point ${i + 1} of segment`);
    }
  }
  
  lines.push('}');
  lines.push('');
  
  lines.push(`
-- Experimental Copter GUIDED controller. One canvas unit = one metre.
-- x = North, y = East relative to EKF origin; altitude = -Down.
-- Dry run only logs; it never commands motion or touches relays.
local current_point = 1
local started = nil
local waiting_until = nil
local finished = false
local function vector(x, y, z)
  local v = Vector3f()
  v:x(x); v:y(y); v:z(z)
  return v
end
local function light(on)
  if DRY_RUN then return end
  if on then relay:on(RELAY_INDEX) else relay:off(RELAY_INDEX) end
end
local function stop(reason)
  light(false)
  if not DRY_RUN and arming:is_armed() and vehicle:get_mode() == 4 then
    vehicle:set_target_velocity_NED(vector(0, 0, 0))
  end
  finished = true
  gcs:send_text(6, reason)
end
function update()
  if finished then return end
  if DRY_RUN then
    gcs:send_text(6, string.format("Preview point %d/%d", current_point, #points))
    current_point = current_point + 1
    if current_point > #points then finished = true; return end
    return update, 100
  end
  if not arming:is_armed() or vehicle:get_mode() ~= 4 then
    stop("Aborted: requires armed Copter GUIDED mode")
    return
  end
  local pos = ahrs:get_relative_position_NED_origin()
  if not pos then stop("Aborted: no EKF position"); return end
  local now = millis():tofloat()
  if not started then started = now end
  if now - started > 120000 then stop("Aborted: target timeout"); return end
  local target = points[current_point]
  local dx, dy, dz = target[1] - pos:x(), target[2] - pos:y(), -ALTITUDE - pos:z()
  local dist = math.sqrt(dx*dx + dy*dy + dz*dz)
  if dist < 0.2 then
    light(false)
    if not vehicle:set_target_velocity_NED(vector(0, 0, 0)) then
      stop("Aborted: command rejected"); return
    end
    if not waiting_until then waiting_until = now + WAIT_TIME * 1000 end
    if now >= waiting_until then
      current_point = current_point + 1
      started = nil
      waiting_until = nil
      if current_point > #points then stop("Light painting complete"); return end
    end
  else
    local speed = target[3] and DRAW_SPEED or MOVE_SPEED
    -- Proportional slowdown near targets, capped by configured speed.
    local scale = math.min(speed, dist) / dist
    light(target[3])
    if not vehicle:set_target_velocity_NED(vector(dx*scale, dy*scale, dz*scale)) then
      stop("Aborted: command rejected"); return
    end
  end
  return update, 100
end
return update, 1000
`);

  return lines.join('\n');
}

/**
 * Export a simplified version for testing (dry run).
 */
export function exportDryRunLua(
  shapes: Shape[],
  config: ExportConfig
): string {
  const dryRunConfig = { ...config, dryRun: true };
  return exportToLua(shapes, dryRunConfig).script;
}

/**
 * Validate the generated Lua script for basic syntax errors.
 * This is a simple check - not a full Lua parser.
 */
export function validateLuaScript(script: string): { valid: boolean; errors: string[] } {
  const errors: string[] = [];
  
  // Check for balanced parentheses
  let parenCount = 0;
  for (const char of script) {
    if (char === '(') parenCount++;
    if (char === ')') parenCount--;
    if (parenCount < 0) {
      errors.push('Unbalanced parentheses: too many closing parentheses');
      break;
    }
  }
  if (parenCount > 0) {
    errors.push('Unbalanced parentheses: too many opening parentheses');
  }
  
  // Check for balanced brackets
  let bracketCount = 0;
  for (const char of script) {
    if (char === '[') bracketCount++;
    if (char === ']') bracketCount--;
    if (bracketCount < 0) {
      errors.push('Unbalanced brackets: too many closing brackets');
      break;
    }
  }
  if (bracketCount > 0) {
    errors.push('Unbalanced brackets: too many opening brackets');
  }
  
  // Check for balanced braces
  let braceCount = 0;
  for (const char of script) {
    if (char === '{') braceCount++;
    if (char === '}') braceCount--;
    if (braceCount < 0) {
      errors.push('Unbalanced braces: too many closing braces');
      break;
    }
  }
  if (braceCount > 0) {
    errors.push('Unbalanced braces: too many opening braces');
  }
  
  // Check for required functions
  if (!script.includes('function update()')) {
    errors.push('Missing required function: update()');
  }
  
  if (!script.includes('return update')) {
    errors.push('Missing required return statement for update function');
  }
  
  // Check for required variables
  if (!script.includes('DRAW_SPEED')) {
    errors.push('Missing required variable: DRAW_SPEED');
  }
  
  if (!script.includes('MOVE_SPEED')) {
    errors.push('Missing required variable: MOVE_SPEED');
  }
  
  if (!script.includes('ALTITUDE')) {
    errors.push('Missing required variable: ALTITUDE');
  }
  
  return {
    valid: errors.length === 0,
    errors,
  };
}
